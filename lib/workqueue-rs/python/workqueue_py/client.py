    def claim(
        self,
        queue: str,
        batch_size: int = 1,
        timeout_ms: int = 5000,
    ) -> list[Message]:
        """Claim messages from a queue.

        Args:
            queue: Queue name to claim from
            batch_size: Maximum number of messages to claim
            timeout_ms: Wait timeout in milliseconds (0 = no wait)

        Returns:
            List of claimed messages (may be empty if queue is empty)

        Raises:
            grpc.RpcError: If the request fails
        """
        self._check_connected()

        request = pb2.ClaimRequest(
            queue=queue,
            worker_id=self.worker_id,
            lease_id=self.lease_id,
            batch_size=batch_size,
            timeout_ms=timeout_ms,
        )

        response = self._stub.Claim(request)
        messages = [Message.from_proto(m) for m in response.messages]
        if messages:
            if len(response.claim_tokens) != len(messages):
                raise RuntimeError(
                    "Claim response missing claim_tokens or length mismatch "
                    f"(messages={len(messages)}, claim_tokens={len(response.claim_tokens)})"
                )
            for msg, token in zip(messages, response.claim_tokens, strict=True):
                msg.claim_token = token
        return messages

    def ack(
        self,
        queue: str,
        msg_ids: list[str],
        claim_tokens: list[str] | None = None,
        state_namespace: str | None = None,
        state_puts: dict[str, bytes] | None = None,
        state_deletes: list[str] | None = None,
    ) -> int:
        """Acknowledge messages as processed, optionally with atomic state updates.

        Args:
            queue: Queue name
            msg_ids: List of message IDs to acknowledge
            claim_tokens: List of claim tokens (1:1 with msg_ids)
            state_namespace: Optional namespace for state updates (e.g., "{job_id}/{stage_id}")
            state_puts: Optional dict of state key -> value to set
            state_deletes: Optional list of state keys to delete

        Returns:
            Number of messages successfully acknowledged

        Raises:
            grpc.RpcError: If the request fails
        """
        self._check_connected()

        if msg_ids:
            if not claim_tokens or len(claim_tokens) != len(msg_ids):
                raise ValueError(
                    "claim_tokens is required and must match msg_ids length "
                    f"(msg_ids={len(msg_ids)}, "
                    f"claim_tokens={len(claim_tokens) if claim_tokens else 0})"
                )

        request = pb2.AckRequest(
            queue=queue,
            msg_ids=msg_ids,
            worker_id=self.worker_id,
            lease_id=self.lease_id,
            state_namespace=state_namespace or "",
            state_puts=state_puts or {},
            state_deletes=state_deletes or [],
            claim_tokens=claim_tokens or [],
        )

        response = self._stub.Ack(request)
        if response.failed_ids:
            logger.warning(f"Failed to ack message IDs: {response.failed_ids}")
        return response.acked_count

    def nack(
        self,
        queue: str,
        msg_ids: list[str],
        claim_tokens: list[str] | None = None,
        reason: str = "processing_failed",
        delay_ms: int = 0,
        state_namespace: str | None = None,
        state_puts: dict[str, bytes] | None = None,
        state_deletes: list[str] | None = None,
    ) -> int:
        """Return messages to queue for retry.

        Args:
            queue: Queue name
            msg_ids: List of message IDs to return
            claim_tokens: List of claim tokens (1:1 with msg_ids)
            reason: Reason for nack ("processing_failed", "payload_missing", "skip")
            delay_ms: Delay before message can be reclaimed
            state_namespace: Optional namespace for atomic state updates
            state_puts: State keys to set atomically with nack
            state_deletes: State keys to delete atomically with nack

        Returns:
            Number of messages returned to queue

        Raises:
            grpc.RpcError: If the request fails
        """
        self._check_connected()

        if msg_ids:
            if not claim_tokens or len(claim_tokens) != len(msg_ids):
                raise ValueError(
                    "claim_tokens is required and must match msg_ids length "
                    f"(msg_ids={len(msg_ids)}, "
                    f"claim_tokens={len(claim_tokens) if claim_tokens else 0})"
                )

        reason_enum = {
            "processing_failed": pb2.NACK_REASON_PROCESSING_FAILED,
            "payload_missing": pb2.NACK_REASON_PAYLOAD_MISSING,
            "skip": pb2.NACK_REASON_SKIP,
        }.get(reason, pb2.NACK_REASON_UNSPECIFIED)

        request = pb2.NackRequest(
            queue=queue,
            msg_ids=msg_ids,
            worker_id=self.worker_id,
            lease_id=self.lease_id,
            reason=reason_enum,
            delay_ms=delay_ms,
            claim_tokens=claim_tokens or [],
            state_namespace=state_namespace or "",
            state_puts=state_puts or {},
            state_deletes=state_deletes or [],
        )

        response = self._stub.Nack(request)
        return response.nacked_count

    def ack_and_forward(
        self,
        upstream_queue: str,
        upstream_msg_ids: list[str],
        upstream_claim_tokens: list[str] | None,
        downstream_queue: str,
        downstream_payloads: list[bytes],
        state_namespace: str | None = None,
        state_puts: dict[str, bytes] | None = None,
        state_deletes: list[str] | None = None,
    ) -> list[str]:
        """Atomically ack upstream messages, push to downstream, and update state.

        This is the key operation for exactly-once semantics between stages.

        Args:
            upstream_queue: Queue to ack from
            upstream_msg_ids: Message IDs to acknowledge
            upstream_claim_tokens: Claim tokens (1:1 with upstream_msg_ids)
            downstream_queue: Queue to push to
            downstream_payloads: Payloads for new downstream messages
            state_namespace: Optional namespace for state updates
            state_puts: Optional dict of state key -> value to set
            state_deletes: Optional list of state keys to delete

        Returns:
            List of new downstream message IDs

        Raises:
            RuntimeError: If the operation fails
            grpc.RpcError: If the request fails
        """
        self._check_connected()

        if upstream_msg_ids:
            if not upstream_claim_tokens or len(upstream_claim_tokens) != len(upstream_msg_ids):
                raise ValueError(
                    "upstream_claim_tokens is required and must match upstream_msg_ids length "
                    f"(upstream_msg_ids={len(upstream_msg_ids)}, "
                    f"upstream_claim_tokens="
                    f"{len(upstream_claim_tokens) if upstream_claim_tokens else 0})"
                )

        request = pb2.AckAndForwardRequest(
            upstream_queue=upstream_queue,
            upstream_msg_ids=upstream_msg_ids,
            downstream_queue=downstream_queue,
            downstream_payloads=downstream_payloads,
            worker_id=self.worker_id,
            lease_id=self.lease_id,
            state_namespace=state_namespace or "",
            state_puts=state_puts or {},
            state_deletes=state_deletes or [],
            upstream_claim_tokens=upstream_claim_tokens or [],
        )

        response = self._stub.AckAndForward(request)
        if not response.success:
            raise RuntimeError("AckAndForward failed")
        return list(response.new_msg_ids)

