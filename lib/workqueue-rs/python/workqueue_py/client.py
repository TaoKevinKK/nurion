@dataclass
class Message:
    """A message claimed from the queue."""

    msg_id: str
    queue: str
    payload: bytes
    created_at: float
    metadata: dict[str, str] = field(default_factory=dict)
    claim_token: str | None = None

    @classmethod
    def from_proto(cls, proto: Any) -> Message:
        """Create Message from protobuf."""
        return cls(
            msg_id=proto.msg_id,
            queue=proto.queue,
            payload=proto.payload,
            created_at=proto.created_at,
            metadata=dict(proto.metadata),
        )


class WorkQueueClient:
    """Python client for WorkQueue server.

    This client provides a simple interface to interact with the WorkQueue
    gRPC server. It handles heartbeat management automatically.

    Example:
        client = WorkQueueClient("localhost:50051", worker_id="worker-0")
        client.start()

        # Push messages
        msg_id = client.push("my-queue", b"hello world")

        # Claim and process messages
        messages = client.claim("my-queue", batch_size=10)
        for msg in messages:
            # Process message
            process(msg.payload)

        # Acknowledge processed messages
        client.ack("my-queue", [m.msg_id for m in messages])

        client.stop()
    """

    def __init__(
        self,
        server_address: str,
        worker_id: str,
        heartbeat_interval_secs: float = 5.0,
        connect_timeout_secs: float = 10.0,
    ):
        """Initialize the client.

        Args:
            server_address: Server address in "host:port" format
            worker_id: Unique identifier for this worker
            heartbeat_interval_secs: Interval between heartbeat pings
            connect_timeout_secs: Timeout for initial connection
        """
        self.server_address = server_address
        self.worker_id = worker_id
        self.heartbeat_interval = heartbeat_interval_secs
        self.connect_timeout = connect_timeout_secs

        self._channel: grpc.Channel | None = None
        self._stub: Any | None = None
        self._lease_id: str = ""

        # Heartbeat management
        self._heartbeat_thread: threading.Thread | None = None
        self._heartbeat_running = False
        self._heartbeat_lock = threading.Lock()

    def start(self) -> None:
        """Connect to server and start heartbeat.

        Raises:
            RuntimeError: If connection or lease acquisition fails
        """
        if pb2 is None or pb2_grpc is None:
            raise RuntimeError(
                "gRPC stubs not generated. Run: "
                "python -m grpc_tools.protoc -I proto --python_out=python/workqueue_py "
                "--grpc_python_out=python/workqueue_py proto/workqueue.proto"
            )

        self._channel = grpc.insecure_channel(self.server_address)
        self._stub = pb2_grpc.WorkQueueStub(self._channel)

        # Start heartbeat stream
        self._heartbeat_running = True
        self._heartbeat_thread = threading.Thread(
            target=self._heartbeat_loop,
            daemon=True,
            name=f"heartbeat-{self.worker_id}",
        )
        self._heartbeat_thread.start()

        # Wait for initial lease
        deadline = time.time() + self.connect_timeout
        while time.time() < deadline:
            if self._lease_id:
                logger.info(f"Connected to {self.server_address}, lease_id={self._lease_id}")
                return
            time.sleep(0.1)

        raise RuntimeError(f"Failed to acquire lease from server within {self.connect_timeout}s")

    def stop(self) -> None:
        """Stop heartbeat and close connection."""
        self._heartbeat_running = False

        if self._heartbeat_thread:
            self._heartbeat_thread.join(timeout=2.0)
            self._heartbeat_thread = None

        if self._channel:
            self._channel.close()
            self._channel = None

        self._stub = None
        self._lease_id = ""
        logger.info(f"Disconnected from {self.server_address}")

    def _heartbeat_loop(self) -> None:
        """Background thread for heartbeat streaming."""
        reconnect_attempts = 0

        def ping_generator() -> Iterator[Any]:
            while self._heartbeat_running:
                yield pb2.HeartbeatPing(
                    worker_id=self.worker_id,
                    lease_id=self._lease_id,
                    timestamp=int(time.time() * 1000),
                )
                time.sleep(self.heartbeat_interval)

        while self._heartbeat_running:
            try:
                responses = self._stub.HeartbeatStream(ping_generator())
                for pong in responses:
                    if not self._heartbeat_running:
                        break
                    with self._heartbeat_lock:
                        self._lease_id = pong.lease_id
                        reconnect_attempts = 0  # Reset on successful connection
                        if not pong.ok:
                            logger.warning("Lease invalidated by server")
                            self._lease_id = ""
            except grpc.RpcError:
                if self._heartbeat_running:
                    reconnect_attempts += 1
                    # Only log first attempt as warning, rest as debug to reduce noise
                    if reconnect_attempts == 1:
                        logger.warning("Heartbeat disconnected, reconnecting...")
                    elif reconnect_attempts % 10 == 0:
                        logger.debug(f"Heartbeat reconnect attempt {reconnect_attempts}")
                    time.sleep(1.0)

    @property
    def lease_id(self) -> str:
        """Get current lease ID."""
        with self._heartbeat_lock:
            return self._lease_id

    def _check_connected(self) -> None:
        """Verify client is connected."""
        if not self._stub:
            raise RuntimeError("Client not started. Call start() first.")

